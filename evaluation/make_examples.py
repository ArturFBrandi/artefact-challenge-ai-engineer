def git_commit() -> str:
    output = subprocess.run(
        ["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=False
    )
    return output.stdout.strip() or "unknown"


def render(
    conversation: Conversation, settings: Settings, provider: LLMProvider, workdir: Path
) -> str:
    db_path = workdir / f"{conversation.slug}.db"
    ingest(db_path, settings.data_dir)
    configured = settings.model_copy(update={"db_path": db_path, "trace_dir": workdir / "traces"})
    service = AgentService(
        configured,
        provider,
        FrozenClock(datetime.fromisoformat(conversation.clock)),
        load_rules(settings.config_dir),
        load_facts(settings.config_dir),
    )
    lines = [
        f"# {conversation.title}",
        "",
        f"Generated by `make examples` on {date.today()}. Model: {settings.llm_model}. "
        f"Commit: {git_commit()}. Store clock: {conversation.clock}.",
        "",
        conversation.demonstrates,
        "",
    ]
    session_id = service.create_session()
    for message in conversation.messages:
        turn = service.handle_message(session_id, message)
        tools = ", ".join(tool["name"] for tool in turn.debug["tools"]) or "none"
        lines += [
            f"**Customer:** {message}",
            "",
            f"**Tom:** {turn.reply}",
            "",
            f"<sub>Tools: {tools}</sub>",
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    settings = Settings()
    try:
        provider = build_provider(settings)
    except ConfigurationError as error:
        print(f"NOT RUN: {error}\nNo examples were generated.", file=sys.stderr)
        return 2
    OUTPUT.mkdir(exist_ok=True)
    with tempfile.TemporaryDirectory() as temporary:
        for conversation in CONVERSATIONS:
            text = render(conversation, settings, provider, Path(temporary))
            path = OUTPUT / f"{conversation.slug}.md"
            path.write_text(text, encoding="utf-8")
            print(f"Wrote {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
